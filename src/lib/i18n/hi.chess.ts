const LEVEL_TIME = (m: RegExpExecArray) => `${m[1]}: हर खिलाड़ी के मिनट, और हर चाल पर जुड़ने वाले सेकंड`;
const JUDGE: Record<string, string> = { 'an inaccuracy': 'अशुद्धि', 'a mistake': 'ग़लती', 'a blunder': 'भारी भूल' };

export const P: Pattern[] = [
  [/^How to play Chess$/, 'शतरंज कैसे खेलें'],
  [/^Your move · (\d+)s to start$/, 'आपकी चाल · शुरू करने को $1 सेकंड'],
  [/^(👀 )?(White|Black) to move$/, (m) => `${m[1] ?? ''}${SIDE[m[2]]} की चाल`],
  [/^You are (White|Black)$/, (m) => `आप ${SIDE[m[1]]} हैं`],
  [/^(\d+\+\d+): minutes each, plus seconds added per move$/, LEVEL_TIME],
  [/^You play (white|black)$/, (m) => `आप ${m[1] === 'white' ? 'सफ़ेद' : 'काले'} से खेलेंगे`],
  [/^Level (\d): plays at about (\d+)$/, 'लेवल $1: लगभग $2 जैसा खेलता है'],
  [/^Level (\d)$/, 'लेवल $1'],
  [/^🤖 Level (\d)$/, '🤖 लेवल $1'],
  [/^♟️ (\d+) moves · 🏁 (\d+) checkmates$/, '♟️ $1 चालें · 🏁 $2 शह-मात'],
  [/^♟️ (.+) · (.+)$/, (m, tr) => `♟️ ${tr(m[1])} · ${tr(m[2])}`],
  [/^(White wins|Black wins|Draw) · (.+)$/, (m, tr) => `${tr(m[1])} · ${tr(m[2])}`],
  [/^thinking · depth (\d+)$/, 'सोच रहा है · गहराई $1'],
  [/^depth (\d+)$/, 'गहराई $1'],
  [/^🧠 Reviewing the game… (\d+) \/ (\d+)$/, '🧠 गेम की समीक्षा… $1 / $2'],
  [/^(\S+) was (an inaccuracy|a mistake|a blunder)\. Best was (\S+)$/, (m) => `${m[1]} एक ${JUDGE[m[2]]} थी। सबसे अच्छी चाल ${m[3]} थी`],
];
